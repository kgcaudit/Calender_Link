"""Provisional OLO Calendar launcher mark (concept A: a brushed calendar sheet,
two binding-ring strokes, and one ink dot for "today").

The OLO family rule is that launcher marks live in kgcaudit/OLO-Design and apps
only pull them. Until the design session adds a `calendar` mark there, this
script borrows OLO-Design's own brush primitives and shared clay ground so the
icon already belongs to the family. Move `mark_calendar` into
OLO-Design/appicons/launcher.py and delete this file once it lands.

    python3 tools/provisional_launcher.py <path-to-olo-design> \
        --out composeApp/src/androidMain/res/drawable
"""
import argparse
import math
import importlib.util
import pathlib


def load_launcher(design_root):
    path = pathlib.Path(design_root) / "appicons" / "launcher.py"
    spec = importlib.util.spec_from_file_location("olo_launcher", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def mark_calendar(L):
    s = []
    # the sheet: a filled mass, slightly bowed, like the Explorer document
    sheet = [(162, 196), (350, 188), (356, 372), (168, 380)]
    s.append((L.fillpoly(sheet, bow=3, jit=1.6), L.FILL))
    for a, b in zip(sheet, sheet[1:] + sheet[:1]):
        s += L.dbl(a, ((a[0] + b[0]) / 2, (a[1] + b[1]) / 2), b, 5.0, L.CT, j=2.4)
    # header band: the defining edge, strongest ink
    s.append((L.seg((164, 238), (258, 232), (352, 230), 6.0, 1.6), L.FOLD))
    # binding rings: two short pressed strokes crossing the top edge
    s.append((L.seg((214, 162), (215, 184), (216, 210), 9.0, 3.0), L.FOLD))
    s.append((L.seg((298, 158), (297, 182), (296, 206), 9.0, 3.0), L.FOLD))
    # faint week rules
    for y in (282, 326):
        s.append(L.wline((182, y), (338, y - 3), 2.4, L.FINE))
    # today: one solid ink dot, like a seal pressed on the sheet
    dot = [(292 + 17 * math.cos(math.radians(a)) * (1.0 + 0.06 * math.sin(math.radians(3 * a))),
            304 + 16 * math.sin(math.radians(a))) for a in range(0, 360, 12)]
    s.append((L._polygon(dot), 0.96))
    return s


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("design_root")
    ap.add_argument("--out", type=pathlib.Path, required=True)
    args = ap.parse_args()
    L = load_launcher(args.design_root)
    strokes, r0, k = L.fit_to_safe(mark_calendar(L))
    r = L.max_radius(strokes)
    if r > L.SAFE + 0.5:
        raise SystemExit(f"calendar: mark reaches radius {r:.1f} > safe {L.SAFE:.1f}")
    note = "<!-- Provisional: tools/provisional_launcher.py (move the mark to OLO-Design). Do not edit by hand. -->"
    vec = L.mark_vector(strokes).replace(
        "<!-- Generated by appicons/launcher.py. Do not edit by hand. -->", note)
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "ic_launcher_background.xml").write_text(L.BACKGROUND_XML, encoding="utf-8")
    (args.out / "ic_launcher_foreground.xml").write_text(vec, encoding="utf-8")
    (args.out / "ic_launcher_monochrome.xml").write_text(vec, encoding="utf-8")
    print(f"calendar: maxR {r:.1f} / safe {L.SAFE:.1f} (fit x{k:.3f} from {r0:.1f})")


if __name__ == "__main__":
    main()
