// Generates the Korean lunar (dangi) month table used by KoreanLunar.kt.
// Source: ICU's dangi calendar (UTC+9 meridian, as KASI publishes), via Node's Intl.
// Spot-checked against Samsung Calendar's lunar labels and published 설날/추석 dates
// (see KoreanLunarTest). Re-run only to widen the range:
//   node tools/gen_lunar_table.mjs 1950 2060 > composeApp/src/commonMain/kotlin/app/olo/calendar/model/KoreanLunarTable.kt
const [from, to] = process.argv.slice(2).map(Number);
const fmt = new Intl.DateTimeFormat("ko-KR-u-ca-dangi", { timeZone: "Asia/Seoul", year: "numeric", month: "numeric", day: "numeric" });
const DAY = 86400000;
const months = []; // {year, month, leap, start}
for (let t = Date.UTC(from - 1, 11, 1); t <= Date.UTC(to + 1, 2, 1); t += DAY) {
  const p = Object.fromEntries(fmt.formatToParts(new Date(t + 3 * 3600000)).map(x => [x.type, x.value]));
  if (p.day !== "1") continue;
  const leap = p.month.startsWith("윤");
  months.push({ year: +p.relatedYear, month: +p.month.replace("윤", ""), leap, start: Math.round(t / DAY) });
}
const years = [];
for (let y = from; y <= to; y++) {
  const ms = months.filter(m => m.year === y);
  const next = months.find(m => m.year === y + 1 && m.month === 1 && !m.leap);
  if (ms.length < 12 || !next || ms[0].month !== 1) throw new Error("incomplete year " + y);
  let bits = 0, leapMonth = 0;
  ms.forEach((m, i) => {
    const end = i + 1 < ms.length ? ms[i + 1].start : next.start;
    const len = end - m.start;
    if (len !== 29 && len !== 30) throw new Error(`bad length ${len} in ${y}/${m.month}`);
    if (len === 30) bits |= 1 << i;
    if (m.leap) leapMonth = m.month;
  });
  years.push([ms[0].start, leapMonth, bits]);
}
const rows = years.map(([s, l, b]) => `        ${s}, ${l}, ${b},`).join("\n");
console.log(`package app.olo.calendar.model

// Generated by tools/gen_lunar_table.mjs from ICU's dangi (Korean) calendar. Do not edit by hand.
// One triple per lunar year from FIRST_YEAR: [solar epoch day of 1/1, leap month (0 = none),
// bit i set when the i-th month of the year (leap month counted in place) has 30 days].
internal object KoreanLunarTable {
    const val FIRST_YEAR = ${from}
    const val LAST_YEAR = ${to}
    val DATA = intArrayOf(
${rows}
    )
}`);
